def error_response(
    *,
    code: str,
    message: str,
    status_code: int,
    params: dict | None = None,
    reason: str | None = None,
    **extra,
):
    payload = {
        'error': message,
        'message': message,
        'error_code': code,
        'params': params or {},
    }
    if reason:
        payload['reason'] = reason
    payload.update(extra)
    return Response(payload, status=status_code)
